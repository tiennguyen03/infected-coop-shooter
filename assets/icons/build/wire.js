// Wire uploaded icon ids into the game.
//   node assets/icons/build/wire.js
// Reads build/uploaded_ids.json (written by upload.js) and rewrites
//   - src/shared/CallInDefinitions.luau, src/shared/UpgradeDefinitions.luau:
//     IconId = "rbxassetid://<imageId>" on the row whose Id equals the icon name
//     (name a new icon after its call-in or card id, e.g. "medkit")
//   - assets/icons/ASSET_IDS.md: every uploaded icon, and which rows use its image id
// The 24 legacy icons are named after the old items; the rows that reuse them keep their
// current IconId, since no row has a legacy name as its Id.

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..", "..", "..");
const IDS_FILE = path.join(__dirname, "uploaded_ids.json");
const DEFS = ["CallInDefinitions.luau", "UpgradeDefinitions.luau"].map((f) => path.join(ROOT, "src", "shared", f));
const TABLE = path.join(ROOT, "assets", "icons", "ASSET_IDS.md");

if (!fs.existsSync(IDS_FILE)) {
	console.error("no " + IDS_FILE + " — run upload.js first");
	process.exit(1);
}
const ids = JSON.parse(fs.readFileSync(IDS_FILE, "utf8"));

let changed = 0;
const usedBy = {}; // imageId -> [row id]
for (const file of DEFS) {
	let src = fs.readFileSync(file, "utf8");
	for (const [id, r] of Object.entries(ids)) {
		if (!r.imageId) continue;
		// The row's own IconId: from `Id = "<id>",` to the first IconId before the next Id.
		const re = new RegExp(`(Id = "${id}",(?:(?![^A-Za-z]Id = ")[\\s\\S])*?IconId = ")rbxassetid://\\d+(")`);
		const next = src.replace(re, `$1rbxassetid://${r.imageId}$2`);
		if (next !== src) {
			changed++;
			src = next;
		}
	}
	fs.writeFileSync(file, src);
	for (const row of src.split(/(?<![A-Za-z])(?=Id = ")/)) {
		const id = /^Id = "([a-z_]+)"/.exec(row);
		const icon = /IconId = "rbxassetid:\/\/(\d+)"/.exec(row);
		if (id && icon) (usedBy[icon[1]] = usedBy[icon[1]] || []).push(id[1]);
	}
}

const rows = Object.entries(ids).map(([name, r]) => {
	const users = r.imageId && usedBy[r.imageId] ? usedBy[r.imageId].join(", ") : "";
	return `| ${name} | ${r.decalId || ""} | ${r.imageId || ""} | ${users} |`;
});
const table = [
	"# Uploaded icon asset IDs",
	"",
	"Uploaded via Open Cloud (creator: PEPPERROCKET / 67169996) with",
	"`assets/icons/build/upload.js`; wired with `wire.js`. Use the **image** id",
	"(`rbxassetid://<imageId>`) in a `CallInDefinitions` / `UpgradeDefinitions` row's `IconId`;",
	"the decal id is the container asset shown on the Creator dashboard. Style spec: docs/STYLES.md.",
	"Icon names are the old item names for the first 24; \"Used by\" lists the rows that show each one.",
	"",
	"| Icon | Decal ID | Image ID (use this) | Used by |",
	"|---|---|---|---|",
	...rows,
	"",
	"SVG sources are generated by `assets/icons/build/icons.js` (PNGs are gitignored).",
	"",
].join("\n");
fs.writeFileSync(TABLE, table);
console.log(`wired ${changed} IconId values; table has ${rows.length} rows`);
